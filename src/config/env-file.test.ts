import { describe, expect, it } from "vitest";
import { parseEnvFile, upsertEnvValue } from "./env-file";

describe("parseEnvFile", () => {
  it("parses bare values and strips surrounding double quotes", () => {
    expect(
      parseEnvFile([
        "DATABASE_PATH=./data/database/soli-isle.sqlite",
        'AUTHOR_PASSWORD_HASH="$argon2id$v=19$m=65536,t=3,p=4$abc$def"',
        "COUNT=42",
      ].join("\n")),
    ).toEqual({
      DATABASE_PATH: "./data/database/soli-isle.sqlite",
      AUTHOR_PASSWORD_HASH: "$argon2id$v=19$m=65536,t=3,p=4$abc$def",
      COUNT: "42",
    });
  });

  it("ignores blank lines and comments and supports the export prefix", () => {
    expect(
      parseEnvFile([
        "# generated by scripts",
        "",
        "export DATABASE_PATH=/data/database/soli-isle.sqlite",
        "export AUTHOR_PASSWORD_HASH=\"$argon2id$hash\"",
        "# trailing comment",
      ].join("\n")),
    ).toEqual({
      DATABASE_PATH: "/data/database/soli-isle.sqlite",
      AUTHOR_PASSWORD_HASH: "$argon2id$hash",
    });
  });

  it("treats everything after the first equals sign as the bare value", () => {
    expect(parseEnvFile("PASSWORD=one=two=three")).toEqual({ PASSWORD: "one=two=three" });
  });

  it("ignores lines without an assignment and tolerates CRLF endings", () => {
    expect(parseEnvFile("A=1\r\n# comment\r\njust some text\r\nB=2\r\n")).toEqual({
      A: "1",
      B: "2",
    });
  });
});

describe("upsertEnvValue", () => {
  it("replaces an existing bare value with a double-quoted one", () => {
    const content = ["DATABASE_PATH=./data/db.sqlite", "AUTHOR_PASSWORD_HASH=old-hash"].join("\n");

    expect(upsertEnvValue(content, "AUTHOR_PASSWORD_HASH", "$argon2id$new")).toBe(
      ['DATABASE_PATH=./data/db.sqlite', 'AUTHOR_PASSWORD_HASH="$argon2id$new"'].join("\n"),
    );
  });

  it("replaces an existing quoted value", () => {
    const content = 'AUTHOR_PASSWORD_HASH="old-hash"\nDATABASE_PATH=./data/db.sqlite';

    expect(upsertEnvValue(content, "AUTHOR_PASSWORD_HASH", "new-hash")).toBe(
      'AUTHOR_PASSWORD_HASH="new-hash"\nDATABASE_PATH=./data/db.sqlite',
    );
  });

  it("replaces an exported assignment", () => {
    const content = "export AUTHOR_PASSWORD_HASH=old-hash";

    expect(upsertEnvValue(content, "AUTHOR_PASSWORD_HASH", "new-hash")).toBe(
      'AUTHOR_PASSWORD_HASH="new-hash"',
    );
  });

  it("appends the key when missing, adding a separator for content without a trailing newline", () => {
    expect(upsertEnvValue("DATABASE_PATH=./data/db.sqlite", "AUTHOR_PASSWORD_HASH", "new-hash")).toBe(
      'DATABASE_PATH=./data/db.sqlite\nAUTHOR_PASSWORD_HASH="new-hash"\n',
    );

    expect(upsertEnvValue("", "AUTHOR_PASSWORD_HASH", "new-hash")).toBe(
      'AUTHOR_PASSWORD_HASH="new-hash"\n',
    );
  });

  it("appends directly when the content already ends with a newline", () => {
    expect(
      upsertEnvValue("DATABASE_PATH=./data/db.sqlite\n", "AUTHOR_PASSWORD_HASH", "new-hash"),
    ).toBe('DATABASE_PATH=./data/db.sqlite\nAUTHOR_PASSWORD_HASH="new-hash"\n');
  });

  it("preserves comments, other variables and their order", () => {
    const content = [
      "# deployment configuration",
      "",
      "export DATABASE_PATH=./data/db.sqlite",
      "RESOURCE_DIR=./data/images",
      "AUTHOR_PASSWORD_HASH=\"old-hash\"",
      "",
      "# end",
    ].join("\n");

    expect(upsertEnvValue(content, "AUTHOR_PASSWORD_HASH", "new-hash")).toBe(
      [
        "# deployment configuration",
        "",
        "export DATABASE_PATH=./data/db.sqlite",
        "RESOURCE_DIR=./data/images",
        'AUTHOR_PASSWORD_HASH="new-hash"',
        "",
        "# end",
      ].join("\n"),
    );
  });

  it("round-trips through parseEnvFile", () => {
    const updated = upsertEnvValue(
      'DATABASE_PATH=./data/db.sqlite\nAUTHOR_PASSWORD_HASH="$argon2id$v=19$old"',
      "AUTHOR_PASSWORD_HASH",
      "$argon2id$v=19$new",
    );

    expect(parseEnvFile(updated).AUTHOR_PASSWORD_HASH).toBe("$argon2id$v=19$new");
    expect(parseEnvFile(updated).DATABASE_PATH).toBe("./data/db.sqlite");
  });
});
